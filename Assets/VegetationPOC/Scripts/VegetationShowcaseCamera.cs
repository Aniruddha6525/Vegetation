using System;
using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Presentation camera for the Vegetation POC scene.
/// Jumps between pre-defined viewpoints (overview, per-biome aerial / ground views),
/// supports an automatic guided tour, free-fly navigation and a minimal on-screen HUD.
///
/// Controls
///   0 / Home      Overview
///   1 - 9         Aerial view of biome N
///   G             Toggle aerial / ground-level view of the current biome
///   Left / Right  Previous / next viewpoint
///   Space         Start / stop the automatic tour
///   RMB + mouse   Look around;  W A S D move,  Q / E down / up,  Shift = fast
///   L             Toggle the floating overview labels
///   H             Toggle HUD
/// </summary>
public class VegetationShowcaseCamera : MonoBehaviour
{
    public enum ViewKind { Overview, Aerial, Ground }

    [Serializable]
    public class Viewpoint
    {
        public string title;
        [TextArea] public string subtitle;
        public ViewKind kind;
        public int biomeIndex = -1;
        public Vector3 position;
        public Vector3 euler;
    }

    [Header("Viewpoints (generated by the POC builder)")]
    public List<Viewpoint> viewpoints = new List<Viewpoint>();

    [Header("Labels")]
    [Tooltip("Floating titles above each terrain; only shown while the camera is high above the scene.")]
    public GameObject overheadLabels;
    public float overheadLabelMinHeight = 110f;
    public bool showOverheadLabels = true;

    [Header("Motion")]
    public float transitionTime = 2.4f;
    public float tourDwellTime = 7f;
    public float tourDriftSpeed = 1.2f;
    public float flySpeed = 22f;
    public float lookSensitivity = 2.2f;

    [Header("HUD")]
    public bool showHud = true;
    public string projectTitle = "Vegetation Showcase  ·  POC";

    int _current;
    bool _touring;
    float _dwellTimer;

    bool _transitioning;
    float _t;
    Vector3 _fromPos, _toPos;
    Quaternion _fromRot, _toRot;

    float _yaw, _pitch;

    GUIStyle _titleStyle, _subtitleStyle, _smallStyle, _headerStyle;
    Texture2D _panelTex, _accentTex;

    void Start()
    {
        DynamicGI.UpdateEnvironment();
        if (viewpoints.Count > 0)
            SnapTo(0);
    }

    void Update()
    {
        HandleKeys();

        bool flying = HandleFreeFly();

        if (_transitioning)
        {
            _t += Time.deltaTime / Mathf.Max(0.01f, transitionTime);
            float e = Mathf.SmoothStep(0f, 1f, Mathf.Clamp01(_t));
            transform.SetPositionAndRotation(Vector3.Lerp(_fromPos, _toPos, e), Quaternion.Slerp(_fromRot, _toRot, e));
            if (_t >= 1f)
            {
                _transitioning = false;
                SyncYawPitch();
            }
        }
        else if (_touring && !flying)
        {
            var vp = CurrentViewpoint;
            if (vp != null && vp.kind == ViewKind.Aerial)
                transform.position += transform.forward * (tourDriftSpeed * Time.deltaTime);

            _dwellTimer += Time.deltaTime;
            if (_dwellTimer >= tourDwellTime)
                GoTo((_current + 1) % viewpoints.Count);
        }

        if (overheadLabels != null)
        {
            bool show = showOverheadLabels && transform.position.y >= overheadLabelMinHeight;
            if (overheadLabels.activeSelf != show)
                overheadLabels.SetActive(show);
        }
    }

    Viewpoint CurrentViewpoint => (_current >= 0 && _current < viewpoints.Count) ? viewpoints[_current] : null;

    void HandleKeys()
    {
        if (viewpoints.Count == 0)
            return;

        if (Input.GetKeyDown(KeyCode.Alpha0) || Input.GetKeyDown(KeyCode.Keypad0) || Input.GetKeyDown(KeyCode.Home))
            UserGoTo(FindView(-1, ViewKind.Overview));

        for (int i = 0; i < 9; i++)
        {
            if (Input.GetKeyDown(KeyCode.Alpha1 + i) || Input.GetKeyDown(KeyCode.Keypad1 + i))
            {
                int idx = FindView(i, ViewKind.Aerial);
                if (idx >= 0)
                    UserGoTo(idx);
            }
        }

        if (Input.GetKeyDown(KeyCode.G))
        {
            var vp = CurrentViewpoint;
            if (vp != null && vp.biomeIndex >= 0)
            {
                var other = vp.kind == ViewKind.Ground ? ViewKind.Aerial : ViewKind.Ground;
                int idx = FindView(vp.biomeIndex, other);
                if (idx >= 0)
                    UserGoTo(idx);
            }
        }

        if (Input.GetKeyDown(KeyCode.RightArrow) || Input.GetKeyDown(KeyCode.PageDown))
            UserGoTo((_current + 1) % viewpoints.Count);
        if (Input.GetKeyDown(KeyCode.LeftArrow) || Input.GetKeyDown(KeyCode.PageUp))
            UserGoTo((_current - 1 + viewpoints.Count) % viewpoints.Count);

        if (Input.GetKeyDown(KeyCode.Space))
        {
            _touring = !_touring;
            _dwellTimer = 0f;
        }

        if (Input.GetKeyDown(KeyCode.L))
            showOverheadLabels = !showOverheadLabels;
        if (Input.GetKeyDown(KeyCode.H))
            showHud = !showHud;
    }

    bool HandleFreeFly()
    {
        if (!Input.GetMouseButton(1))
            return false;

        if (Input.GetMouseButtonDown(1))
        {
            _transitioning = false;
            _touring = false;
            SyncYawPitch();
        }

        _yaw += Input.GetAxis("Mouse X") * lookSensitivity;
        _pitch = Mathf.Clamp(_pitch - Input.GetAxis("Mouse Y") * lookSensitivity, -89f, 89f);
        transform.rotation = Quaternion.Euler(_pitch, _yaw, 0f);

        var move = Vector3.zero;
        if (Input.GetKey(KeyCode.W)) move += Vector3.forward;
        if (Input.GetKey(KeyCode.S)) move += Vector3.back;
        if (Input.GetKey(KeyCode.A)) move += Vector3.left;
        if (Input.GetKey(KeyCode.D)) move += Vector3.right;
        if (Input.GetKey(KeyCode.E)) move += Vector3.up;
        if (Input.GetKey(KeyCode.Q)) move += Vector3.down;

        float speed = flySpeed * (Input.GetKey(KeyCode.LeftShift) || Input.GetKey(KeyCode.RightShift) ? 4f : 1f);
        transform.position += transform.TransformDirection(move) * (speed * Time.deltaTime);
        return true;
    }

    int FindView(int biome, ViewKind kind)
    {
        for (int i = 0; i < viewpoints.Count; i++)
            if (viewpoints[i].kind == kind && (kind == ViewKind.Overview || viewpoints[i].biomeIndex == biome))
                return i;
        return -1;
    }

    void UserGoTo(int index)
    {
        if (index < 0)
            return;
        _touring = false;
        GoTo(index);
    }

    void GoTo(int index)
    {
        if (index < 0 || index >= viewpoints.Count)
            return;
        _current = index;
        _dwellTimer = 0f;
        _fromPos = transform.position;
        _fromRot = transform.rotation;
        _toPos = viewpoints[index].position;
        _toRot = Quaternion.Euler(viewpoints[index].euler);
        _t = 0f;
        _transitioning = true;
    }

    void SnapTo(int index)
    {
        _current = index;
        transform.SetPositionAndRotation(viewpoints[index].position, Quaternion.Euler(viewpoints[index].euler));
        SyncYawPitch();
    }

    void SyncYawPitch()
    {
        var e = transform.rotation.eulerAngles;
        _yaw = e.y;
        _pitch = e.x > 180f ? e.x - 360f : e.x;
    }

    // ------------------------------------------------------------------ HUD

    void EnsureStyles()
    {
        if (_titleStyle != null)
            return;

        _panelTex = MakeTex(new Color(0.04f, 0.05f, 0.045f, 0.72f));
        _accentTex = MakeTex(new Color(0.55f, 0.78f, 0.42f, 1f));

        _titleStyle = new GUIStyle(GUI.skin.label) { fontStyle = FontStyle.Bold, wordWrap = false };
        _titleStyle.normal.textColor = Color.white;
        _subtitleStyle = new GUIStyle(GUI.skin.label) { wordWrap = true };
        _subtitleStyle.normal.textColor = new Color(0.84f, 0.88f, 0.85f);
        _smallStyle = new GUIStyle(GUI.skin.label) { wordWrap = false };
        _smallStyle.normal.textColor = new Color(0.75f, 0.8f, 0.77f);
        _headerStyle = new GUIStyle(GUI.skin.label) { fontStyle = FontStyle.Bold, alignment = TextAnchor.UpperLeft };
        _headerStyle.normal.textColor = new Color(1f, 1f, 1f, 0.9f);
    }

    static Texture2D MakeTex(Color c)
    {
        var t = new Texture2D(1, 1) { hideFlags = HideFlags.HideAndDontSave };
        t.SetPixel(0, 0, c);
        t.Apply();
        return t;
    }

    void OnGUI()
    {
        if (!showHud || viewpoints.Count == 0)
            return;

        EnsureStyles();
        float s = Screen.height / 1080f;
        _titleStyle.fontSize = Mathf.RoundToInt(40 * s);
        _subtitleStyle.fontSize = Mathf.RoundToInt(21 * s);
        _smallStyle.fontSize = Mathf.RoundToInt(16 * s);
        _headerStyle.fontSize = Mathf.RoundToInt(20 * s);

        GUI.Label(new Rect(28 * s, 22 * s, 900 * s, 40 * s), projectTitle, _headerStyle);

        var vp = CurrentViewpoint;
        if (vp != null)
        {
            string kind = vp.kind == ViewKind.Overview ? "OVERVIEW" : vp.kind == ViewKind.Aerial ? "AERIAL VIEW" : "GROUND VIEW";
            float w = 760 * s, h = 150 * s, x = 28 * s, y = Screen.height - h - 64 * s;
            GUI.DrawTexture(new Rect(x, y, w, h), _panelTex);
            GUI.DrawTexture(new Rect(x, y, 8 * s, h), _accentTex);
            GUI.Label(new Rect(x + 30 * s, y + 14 * s, w - 40 * s, 24 * s), kind + (_touring ? "   ·   TOUR" : ""), _smallStyle);
            GUI.Label(new Rect(x + 30 * s, y + 36 * s, w - 40 * s, 52 * s), vp.title, _titleStyle);
            GUI.Label(new Rect(x + 30 * s, y + 92 * s, w - 48 * s, 54 * s), vp.subtitle, _subtitleStyle);
        }

        GUI.Label(new Rect(28 * s, Screen.height - 44 * s, Screen.width - 56 * s, 30 * s),
            "0 Overview   ·   1-6 Biomes   ·   G Ground/Aerial   ·   ←/→ Next   ·   Space Tour   ·   RMB + WASD/QE Fly   ·   L Labels   ·   H HUD",
            _smallStyle);
    }
}
